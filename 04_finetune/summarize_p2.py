def update_guide(probes, fts, teacher):
    """Rewrite the results block of the newcomer guide from result files, then rebuild its HTML page."""
    import datetime
    import sys
    if not GUIDE.exists():
        return
    rows = ["Updated " + datetime.datetime.now().strftime("%Y-%m-%d %H:%M") + ". Test videos 92/96/103/110/111; rows "
            "without \"OFFICIAL\" are scored on all 10,374 test frames, OFFICIAL rows on the 7,815 frames with a triplet "
            "(the official protocol, Step 9); brackets are 95% bootstrap CIs. Probe and "
            "fine-tune rows were measured on the RTX 4090 D; the teacher row on the GTX 1070 laptop (same code and data).", "",
            "| What | Test AP_IVT | Source file |", "|---|---|---|"]
    for label, kind, key in GUIDE_ROWS:
        if kind == "mean":
            v = [fts[k]["test"]["mAP_ivt"] for k in key if k in fts]
            src = ", ".join(f"ft_{k}_metrics.json" for k in key)
            cell = (f"**{statistics.mean(v):.1f} ± {statistics.stdev(v):.1f}** (n = {len(v)}; val "
                    + " / ".join(f"{fts[k]['val_at_best']['mAP_ivt']:.2f}" for k in key) + ")") if len(v) == len(key) else "pending"
            rows.append(f"| {label} | {cell} | `{src}` |")
            continue
        if kind == "teacher":
            r = teacher and next(iter(teacher["results"].values()))
            src = "03_pretrain/output/teacher_probe_fulltest.json"
            cell = (f"**{r['test']['mAP_ivt']:.1f}** (val {r['val_best_mAP_ivt']:.1f}; I {r['test']['mAP_i']:.1f}, "
                    f"V {r['test']['mAP_v']:.1f}, T {r['test']['mAP_t']:.1f})") if r else "pending"
        else:
            r = (probes if kind == "probe" else fts).get(key)
            src = f"04_finetune/output/{'probe_' + key if kind == 'probe' else 'ft_' + key + '_metrics'}.json"
            if r:
                t, ci = r["test"], r["test_ci95"].get("ivt")
                cell = (f"**{t['mAP_ivt']:.1f}**" + (f" ({ci[0]:.1f}–{ci[1]:.1f})" if ci else "") +
                        f"; I {t['mAP_i']:.1f}, V {t['mAP_v']:.1f}, T {t['mAP_t']:.1f}")
            else:
                cell = "pending"
        rows.append(f"| {label} | {cell} | `{src}` |")
    g = GUIDE.read_text(encoding="utf8")
    g = re.sub(r"(<!-- results:start[^\n]*-->\n).*?(<!-- results:end -->)",
               lambda m: m.group(1) + "\n".join(rows) + "\n" + m.group(2), g, count=1, flags=re.S)
    GUIDE.write_text(g, encoding="utf8")
    sys.path.insert(0, str(HERE.parent / "06_present"))
    import build_guide_html
    build_guide_html.main()


if __name__ == "__main__":
    main()
