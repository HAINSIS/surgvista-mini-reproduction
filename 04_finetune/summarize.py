"""04_finetune step 2: results table + charts + two 'Validation Trinity' extras (Henriques et al., MedIA 2026).

  - Latency-Aware Accuracy: inference latency per online prediction (batch 1, GTX 1070) next to mAP.
  - Safety-Critical Recall: recall on frames whose ground truth contains a triplet acting on a critical structure
    (cystic artery, cystic duct, blood vessel) - the long-tail classes where a miss matters most.
Writes output/results.md, output/results.png, output/curves.png, ../03_pretrain/output/pretrain_curves.png
"""
import json
import sys
import time
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
import torch  # noqa: E402

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "_shared"))
from clips import clip_index, gather  # noqa: E402
from surgvista_mini import MEAN, STD, VideoViT, load_cfg  # noqa: E402

ARMS = ["scratch", "imagenet", "videomae", "surgvista", "surgvista_in"]
LABEL = {"scratch": "Scratch (no pretraining)", "imagenet": "ImageNet ViT-S (natural images)",
         "videomae": "VideoMAE-mini (surgical video, no distill.)", "surgvista": "SurgVISTA-mini from scratch", "surgvista_in": "SurgVISTA-mini from ImageNet init",
         "endossl_teacher": "EndoSSL ViT-L (surgical image FM, the teacher)", "chance": "Chance"}
# fixed categorical order (validated palette, light mode); colour follows the arm, never its rank
COLOR = {"surgvista": "#2a78d6", "imagenet": "#eb6834", "videomae": "#1baf7a", "scratch": "#eda100",
         "surgvista_in": "#e87ba4", "endossl_teacher": "#008300"}
INK, INK2, GRID, SURF = "#0b0b0b", "#52514e", "#e4e3df", "#fcfcfb"
CRITICAL = ("cystic_artery", "cystic_duct", "blood_vessel")

cfg = load_cfg(); mc = cfg["model"]; dev = "cuda"
out = HERE / "output"
cache = Path(cfg["data"]["cache"]); ck = Path(cfg["work_root"]) / "ckpt"
arms = [a for a in ARMS if (out / f"{a}_metrics.json").exists()]
M = {a: json.load(open(out / f"{a}_metrics.json")) for a in arms}

# ---------- Validation-Trinity extras ----------
df = pd.read_csv(HERE.parent / "02_data" / "output" / "index.csv")
classes = json.load(open(HERE.parent / "02_data" / "output" / "classes.json"))
tri0 = len(classes["instruments"]) + len(classes["verbs"]) + len(classes["targets"])
crit = [tri0 + i for i, t in enumerate(classes["triplets"]) if t.split(",")[-1] in CRITICAL]
te = np.where(df.split.values == "test")[0]
cidx = clip_index(df, mc["num_frames"], mc["sampling_rate"])
Y = np.load(cache / "labels.npy")
frames = torch.from_numpy(np.load(cache / "frames112.npy")).to(dev)
mean, std = MEAN.to(dev), STD.to(dev)
crit_rows = te[Y[te][:, crit].sum(1) > 0]
for a in arms:
    model = VideoViT(cfg["data"]["img_size"], mc["patch"], mc["tubelet"], mc["num_frames"], mc["embed_dim"],
                     mc["depth"], mc["heads"], num_classes=Y.shape[1])
    model.load_state_dict(torch.load(ck / f"ft_{a}.pth")); model.eval().to(dev)
    with torch.no_grad():
        P = torch.cat([torch.sigmoid(model((gather(frames, torch.from_numpy(cidx[crit_rows[i:i + 32]]).to(dev)) - mean) / std)).cpu()
                       for i in range(0, len(crit_rows), 32)]).numpy()
        gt = Y[crit_rows][:, crit].astype(bool)
        # a critical frame counts as caught if the top-5 triplets contain one of its true critical triplets
        top5 = np.argsort(-P[:, tri0:], 1)[:, :5] + tri0
        caught = [any(c in top5[r] for c in np.array(crit)[gt[r]]) for r in range(len(crit_rows))]
        M[a]["SCR_top5"] = float(np.mean(caught)) if len(caught) else float("nan")
        x1 = gather(frames, torch.from_numpy(cidx[te[:1]]).to(dev))
        for _ in range(5): model((x1 - mean) / std)
        torch.cuda.synchronize(); t = time.time()
        for _ in range(30): model((x1 - mean) / std)
        torch.cuda.synchronize(); M[a]["latency_ms"] = (time.time() - t) / 30 * 1000

# ---------- table ----------
lines = ["# Results — CholecT50 triplet recognition (10 held-out videos, CV fold 1)", "",
         f"Auto-generated by summarize.py. Single seed, equal fine-tuning budget per arm. "
         f"Safety-critical frames in test: {len(crit_rows)} (triplets on {', '.join(CRITICAL)}).", "",
         "| Initialisation | mAP_I | mAP_V | mAP_T | **mAP_IVT** | best mAP_IVT | SCR@top5 | latency (ms) | epochs |",
         "|---|---|---|---|---|---|---|---|---|"]
for a in arms:
    m = M[a]
    lines.append(f"| {LABEL[a]} | {100*m['mAP_I']:.1f} | {100*m['mAP_V']:.1f} | {100*m['mAP_T']:.1f} | **{100*m['mAP_IVT']:.1f}** | "
                 f"{100*m['best_mAP_IVT']:.1f} | {100*m['SCR_top5']:.1f} | {m['latency_ms']:.0f} | {m['epochs_run']} |")
lines += ["", "mAP over classes present in the test subset (I: instrument, V: verb, T: target, IVT: full triplet).",
          "SCR@top5 = share of safety-critical frames whose true critical triplet is in the model's top-5.",
          "Latency = one online prediction (16-frame clip, batch 1, fp32, GTX 1070)."]
(out / "results.md").write_text("\n".join(lines), encoding="utf8")
json.dump(M, open(out / "results_all.json", "w"), indent=1)
print("\n".join(lines))

# ---------- charts ----------
plt.rcParams.update({"font.family": "DejaVu Sans", "axes.edgecolor": GRID, "axes.labelcolor": INK2,
                     "xtick.color": INK2, "ytick.color": INK2, "axes.titlecolor": INK, "figure.facecolor": SURF,
                     "axes.facecolor": SURF, "axes.spines.top": False, "axes.spines.right": False})
groups = [("mAP_I", "Instrument"), ("mAP_V", "Verb"), ("mAP_T", "Target"), ("mAP_IVT", "Triplet (IVT)")]
fig, ax = plt.subplots(figsize=(10, 4.6))
w = 0.8 / len(arms); x = np.arange(len(groups))
for i, a in enumerate(arms):
    vals = [100 * M[a][g] for g, _ in groups]
    bars = ax.bar(x + (i - (len(arms) - 1) / 2) * w, vals, w * 0.92, color=COLOR[a], label=LABEL[a], edgecolor=SURF, linewidth=1)
    for b, v in zip(bars, vals):
        ax.text(b.get_x() + b.get_width() / 2, v + 0.6, f"{v:.1f}", ha="center", va="bottom", fontsize=8, color=INK2)
ax.set_xticks(x, [n for _, n in groups], fontsize=11); ax.set_ylabel("test mAP (%)")
ax.yaxis.grid(True, color=GRID, linewidth=0.8); ax.set_axisbelow(True)
ax.legend(frameon=False, fontsize=9, ncol=2, loc="upper right")
ax.set_title("CholecT50 triplet recognition — same model, same fine-tuning budget, different pretraining", fontsize=11, loc="left")
fig.tight_layout(); fig.savefig(out / "results.png", dpi=160); plt.close(fig)

fig, ax = plt.subplots(figsize=(6.2, 4.2))
for a in arms:
    log = pd.read_csv(out / f"{a}_log.csv")
    ax.plot(log.epoch, 100 * log.mAP_IVT, color=COLOR[a], lw=2, marker="o", ms=5, label=LABEL[a])
    ax.annotate(f"{100*log.mAP_IVT.iloc[-1]:.1f}", (log.epoch.iloc[-1], 100 * log.mAP_IVT.iloc[-1]),
                xytext=(6, 0), textcoords="offset points", va="center", fontsize=8, color=INK2)
ax.set_xlabel("fine-tuning epoch"); ax.set_ylabel("test mAP_IVT (%)")
ax.yaxis.grid(True, color=GRID, linewidth=0.8); ax.set_axisbelow(True)
ax.legend(frameon=False, fontsize=8); ax.set_title("Triplet mAP during fine-tuning", fontsize=11, loc="left")
fig.tight_layout(); fig.savefig(out / "curves.png", dpi=160); plt.close(fig)

pre = HERE.parent / "03_pretrain" / "output"
logs = {v: pd.read_csv(pre / f"{v}_log.csv") for v in ["surgvista", "videomae"] if (pre / f"{v}_log.csv").exists()}
if logs:
    fig, axs = plt.subplots(1, 2, figsize=(9, 3.6))
    for v, log in logs.items():
        axs[0].plot(log.epoch, log.loss_vid, color=COLOR[v], lw=2, label=LABEL[v])
    if "surgvista" in logs:
        axs[1].plot(logs["surgvista"].epoch, logs["surgvista"].loss_img, color=COLOR["surgvista"], lw=2, label=LABEL["surgvista"])
    axs[0].set_title("Pixel reconstruction loss (masked cubes)", fontsize=10, loc="left")
    axs[1].set_title("Teacher-feature distillation loss", fontsize=10, loc="left")
    for a_ in axs:
        a_.set_xlabel("pretraining epoch"); a_.yaxis.grid(True, color=GRID, linewidth=0.8); a_.legend(frameon=False, fontsize=8)
    fig.tight_layout(); fig.savefig(pre / "pretrain_curves.png", dpi=160); plt.close(fig)
lp_path = out / "linear_probe.json"
if lp_path.exists():
    LP = json.load(open(lp_path))
    order = [k for k in ["scratch", "imagenet", "videomae", "surgvista", "surgvista_in", "endossl_teacher"] if k in LP]
    fig, axs = plt.subplots(1, 2, figsize=(10.5, 4.2), sharey=True)
    for ax, (g, name) in zip(axs, [("mAP_I", "Instrument presence"), ("mAP_IVT", "Full triplet <I, V, T>")]):
        vals = [100 * LP[k][g] for k in order]
        ys = np.arange(len(order))[::-1]
        ax.barh(ys, vals, 0.7, color=[COLOR[k] for k in order], edgecolor=SURF, linewidth=1)
        for y_, v in zip(ys, vals):
            ax.text(v + 0.5, y_, f"{v:.1f}", va="center", fontsize=9, color=INK2)
        ch = 100 * LP["chance"][g]
        ax.axvline(ch, color=INK2, lw=1.2, ls=(0, (4, 3)))
        ax.set_title(name, fontsize=11, loc="left"); ax.set_xlabel(f"test mAP (%)   ·   dashed line = chance ({ch:.1f})")
        ax.xaxis.grid(True, color=GRID, linewidth=0.8); ax.set_axisbelow(True)
        ax.set_yticks(ys, [LABEL[k] for k in order], fontsize=9)
    fig.suptitle("Linear probe on frozen features (representation quality, no fine-tuning)", fontsize=11, x=0.01, ha="left")
    fig.tight_layout(); fig.savefig(out / "linear_probe.png", dpi=160); plt.close(fig)
print("charts written")
