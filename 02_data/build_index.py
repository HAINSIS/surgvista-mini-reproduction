"""Build the CholecT50 subset: frame index, multi-hot labels, cached frame arrays.

  python 02_data/build_index.py

Reads  : <raw_dir>/samples.json, <raw_dir>/data/<shard>/*.png   (download: see README)
Pins   : 02_data/frames_used.csv = exact (video, frame) list of the reported run, if present
Writes : <cache>/frames112.npy, <cache>/frames224.npy, <cache>/labels.npy
         02_data/output/index.csv, classes.json, data_summary.md
"""
import json
import sys
from pathlib import Path

import cv2
import numpy as np
import pandas as pd
from tqdm import tqdm

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "_shared"))
from surgvista_mini import load_cfg, ROOT  # noqa: E402

cfg = load_cfg()
raw = Path(cfg["data"]["raw_dir"])
cache = Path(cfg["data"]["cache"]); cache.mkdir(parents=True, exist_ok=True)
out = ROOT / "02_data" / "output"; out.mkdir(exist_ok=True)

print("loading samples.json ...")
samples = json.load(open(raw / "samples.json", encoding="utf8"))["samples"]

def complete_png(p):
    """Interrupted parallel downloads can leave truncated files; a complete PNG ends with IEND."""
    if not p.exists() or p.stat().st_size < 100:
        return False
    with open(p, "rb") as f:
        f.seek(-12, 2)
        return b"IEND" in f.read()


def labels(s, key):
    f = s.get(key) or {}
    return [c["label"] for c in (f.get("classifications") or [])]

groups = {k: set() for k in ["instruments", "verbs", "targets", "triplets"]}
rows = []
for s in samples:
    for k in groups:
        groups[k].update(labels(s, k))
    p = raw / s["filepath"].lstrip("./")
    if complete_png(p):
        rows.append({"path": str(p), "video": int(s["video_id"].replace("VID", "")), "frame": int(s["frame_number"]),
                     **{k: "|".join(labels(s, k)) for k in groups}})
classes = {k: sorted(v) for k, v in groups.items()}
json.dump(classes, open(out / "classes.json", "w"), indent=1)
df = pd.DataFrame(rows).sort_values(["video", "frame"]).reset_index(drop=True)
# Pin the exact frames of the reported run (a subset of the four shards); delete the file to use every frame.
pin = ROOT / "02_data" / "frames_used.csv"
if pin.exists():
    keep = pd.read_csv(pin)
    df = df.merge(keep, on=["video", "frame"]).sort_values(["video", "frame"]).reset_index(drop=True)
    print(f"pinned to frames_used.csv: {len(df)} of {len(keep)} listed frames found")
test = set(cfg["data"]["test_videos"])
df["split"] = np.where(df.video.isin(test), "test", "train")
print(len(samples), "samples in dataset;", len(df), "frames on disk;", df.video.nunique(), "videos")

# multi-hot labels in fixed order: instruments | verbs | targets | triplets
Y = np.zeros((len(df), sum(len(v) for v in classes.values())), np.uint8)
off = 0
for k, names in classes.items():
    idx = {n: i for i, n in enumerate(names)}
    for r, cell in enumerate(df[k]):
        for lab in filter(None, cell.split("|")):
            Y[r, off + idx[lab]] = 1
    off += len(names)
np.save(cache / "labels.npy", Y)

S = cfg["data"]["img_size"]
f112 = np.zeros((len(df), S, S, 3), np.uint8)
f224 = np.zeros((len(df), 224, 224, 3), np.uint8)
for i, p in enumerate(tqdm(df.path, desc="decode")):
    im = cv2.cvtColor(cv2.imread(p), cv2.COLOR_BGR2RGB)
    f224[i] = cv2.resize(im, (224, 224), interpolation=cv2.INTER_AREA)
    f112[i] = cv2.resize(im, (S, S), interpolation=cv2.INTER_AREA)
np.save(cache / "frames112.npy", f112)
np.save(cache / "frames224.npy", f224)
df.drop(columns=["path"]).assign(path=df.path).to_csv(out / "index.csv", index=False)

n_cls = {k: len(v) for k, v in classes.items()}
with open(out / "data_summary.md", "w", encoding="utf8") as f:
    f.write("# Data summary (auto-generated by build_index.py)\n\n")
    f.write(f"- Source: HF `{cfg['data']['hf_dataset']}`, shards {cfg['data']['shards']}\n")
    f.write(f"- Frames on disk: {len(df)} from {df.video.nunique()} videos (1 fps)\n")
    for sp in ["train", "test"]:
        d = df[df.split == sp]
        f.write(f"- {sp}: {len(d)} frames, {d.video.nunique()} videos\n")
    f.write(f"- Classes: {n_cls}\n")
    f.write(f"- Test videos (CholecT50 CV fold 1): {sorted(test)}\n")
print(open(out / "data_summary.md").read())
