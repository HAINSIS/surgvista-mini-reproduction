"""04_finetune, phase 2: collect every finished phase-2 result into one table + two figures.

Reads only result files (never typed numbers): output/probe_*.json, output/ft_*_metrics.json,
03_pretrain/output/teacher_probe_fulltest.json. Missing runs are listed as pending.
Writes output/p2_results.md, output/p2_results.json, output/p2_scaling_curve_<start>.png, output/p2_finetune.png

    work/.venv/Scripts/python.exe 04_finetune/summarize_p2.py
"""
import argparse
import json
import re
import statistics
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

HERE = Path(__file__).resolve().parent
OUT = HERE / "output"
PAPER = {"MVD-K400 (paper Table 12)": 35.3, "SurgVISTA, 3.55M frames (paper Table 12)": 41.1,
         "VideoMAE-K400 (paper Table 12)": 33.5}
# dataviz reference palette, light mode (validated: scripts/validate_palette.js, all checks pass)
BLUE, ORANGE = "#2a78d6", "#eb6834"
INK, INK2, GRID, SURF = "#0b0b0b", "#52514e", "#e4e3df", "#fcfcfb"
RUN_LABELS = {"mvd": "MVD-K400 → fine-tune", "svc_mvd_ep4": "MVD-K400 + SurgVISTA 4 ep → fine-tune",
              "mvd_s1": "MVD-K400 → fine-tune (seed 1)", "svc_mvd_ep4_s1": "MVD-K400 + SurgVISTA 4 ep → fine-tune (seed 1)",
              "vmk400": "VideoMAE-K400 → fine-tune",
              "mvd_png": "MVD → fine-tune, original frames", "svc_mvd_long_png": "MVD + long SurgVISTA → fine-tune, original frames",
              "off_mvd": "MVD → official fine-tune code", "off_svc_mvd_long": "MVD + long SurgVISTA → official fine-tune code",
              "off_mvd_amp": "MVD → official code (AMP)", "off_svc_mvd_long_amp": "MVD + long SurgVISTA → official code (AMP)",
              "scr_s_base": "MVD → official code, 10 ep, every 4th clip", "scr_s_stride2": "MVD → official code, 10 ep, every 2nd clip",
              "scr_s_stride2_s1": "same, seed 1", "scr_s_stride2_s2": "same, seed 2",
              "scr_s_all5": "MVD → official code, 5 ep, every clip"}


def load(p):
    return json.loads(p.read_text()) if p.exists() else None


def fmt(m, ci=None):
    if m is None:
        return "_pending_"
    s = f"{m:.1f}"
    return s + (f" ({ci[0]:.1f}–{ci[1]:.1f})" if ci else "")


def style(ax):
    ax.set_facecolor(SURF)
    for s in ["top", "right"]:
        ax.spines[s].set_visible(False)
    for s in ["left", "bottom"]:
        ax.spines[s].set_color(GRID)
    ax.tick_params(colors=INK2, labelsize=9)
    ax.grid(axis="y", color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)


def main():
    global OUT
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default=str(OUT), help="result folder (default 04_finetune/output)")
    OUT = Path(ap.parse_args().dir)
    probes = {p.stem[len("probe_"):]: load(p) for p in sorted(OUT.glob("probe_*.json")) if p.stem != "probe_smoke"}
    fts = {p.stem[len("ft_"):-len("_metrics")]: load(p) for p in sorted(OUT.glob("ft_*_metrics.json"))}
    teacher = load(HERE.parent / "03_pretrain" / "output" / "teacher_probe_fulltest.json")

    lines = ["# Phase-2 results (generated by summarize_p2.py — do not edit by hand)", "",
             "Official CholecT50 challenge split (test videos 92, 96, 103, 110, 111), official ivtmetrics "
             "(`compute_video_AP`, ignore_null). Brackets: 95% bootstrap CI (frames resampled within videos).", "",
             "## Frozen-feature probe (the yardstick for the scaling curve; not the paper's protocol)", "",
             "| run | test AP_IVT | AP_I | AP_V | AP_T | val AP_IVT |", "|---|---|---|---|---|---|"]
    for name, r in probes.items():
        t = r["test"]
        lines.append(f"| {name} | {fmt(t['mAP_ivt'], r['test_ci95'].get('ivt'))} | {t['mAP_i']:.1f} | {t['mAP_v']:.1f} | "
                     f"{t['mAP_t']:.1f} | {r['val_best_mAP_ivt']:.1f} |")
    if teacher:
        for conv, r in teacher["results"].items():
            t = r["test"]
            lines.append(f"| EndoSSL ViT-L teacher, frame-level ({conv}) | {fmt(t['mAP_ivt'])} | {t['mAP_i']:.1f} | "
                         f"{t['mAP_v']:.1f} | {t['mAP_t']:.1f} | {r['val_best_mAP_ivt']:.1f} |")
    lines += ["", "## Fine-tuning (official recipe; budget deviations in each run's meta)", "",
              "| run | test AP_IVT | AP_I | AP_V | AP_T | AP_IV | AP_IT | best-val epoch | train stride |",
              "|---|---|---|---|---|---|---|---|---|"]
    for name, r in fts.items():
        t = r["test"]
        lines.append(f"| {name} | {fmt(t['mAP_ivt'], r['test_ci95'].get('ivt'))} | {t['mAP_i']:.1f} | {t['mAP_v']:.1f} | "
                     f"{t['mAP_t']:.1f} | {t['mAP_iv']:.1f} | {t['mAP_it']:.1f} | {r['best_val_epoch']} | "
                     f"{r['meta'].get('deviations', {}).get('train_stride', '1 (official code)')} |")
    lines += ["", "Paper reference values (ViT-B, full data, full recipe): " +
              "; ".join(f"{k} = {v}" for k, v in PAPER.items()), ""]
    (OUT / "p2_results.md").write_text("\n".join(lines), encoding="utf8")
    (OUT / "p2_results.json").write_text(json.dumps({"probes": probes, "finetune": fts, "teacher": teacher, "paper": PAPER}, indent=1))

    # Figure 1: scaling curve (probe test AP_IVT vs epochs of continued pretraining), one per start weights tag
    for tag in sorted({k.split("_ep")[0] for k in probes if k.endswith("_ep0")}):
        pts = {"with EndoSSL teacher (SurgVISTA)": ("svc", BLUE, "o"), "no teacher (VideoMAE objective)": ("vmc", ORANGE, "s")}
        if f"{tag}_ep0" not in probes:
            continue
        base = probes[f"{tag}_ep0"]["test"]["mAP_ivt"]
        bci = probes[f"{tag}_ep0"]["test_ci95"]["ivt"]
        if not any(f"{pre}_{tag}_ep{e}" in probes for pre, _, _ in pts.values() for e in [1, 2, 4, 8]):
            continue  # only the start point exists yet: no curve to draw
        fig, ax = plt.subplots(figsize=(6.4, 3.8), facecolor=SURF)
        style(ax)
        ends = []
        for label, (pre, color, marker) in pts.items():
            xs, ys, lo, hi = [0], [base], [base - bci[0]], [bci[1] - base]
            for e in [1, 2, 4, 8]:
                r = probes.get(f"{pre}_{tag}_ep{e}")
                if r:
                    v = r["test"]["mAP_ivt"]; ci = r["test_ci95"]["ivt"]
                    xs.append(e); ys.append(v); lo.append(v - ci[0]); hi.append(ci[1] - v)
            if len(xs) == 1:
                continue
            ax.errorbar(xs, ys, yerr=[lo, hi], color=color, marker=marker, markersize=6, linewidth=2, capsize=0,
                        elinewidth=1, markeredgecolor=SURF, markeredgewidth=1.5, zorder=3,
                        linestyle="-" if len(xs) > 2 else (0, (4, 3)),  # dashed = only the end points were measured
                        label=label + ("" if len(xs) > 2 else ", end point only"))
            ends.append((xs[-1], ys[-1]))
        # end labels: nudge apart vertically when two series end at nearly the same value
        for k, (x, y) in enumerate(sorted(ends, key=lambda e: e[1])):
            dy = (-7 if k == 0 else 7) if len(ends) == 2 and abs(ends[0][1] - ends[1][1]) < 0.4 else 0
            ax.annotate(f"{y:.1f}", (x, y), xytext=(8, dy), textcoords="offset points", va="center", fontsize=9, color=INK)
        ax.annotate(f"start {base:.1f}", (0, base), xytext=(8, 4), textcoords="offset points", fontsize=9, color=INK2)
        ax.set_xlabel("epochs of continued pretraining on CholecT50 train (every 4th frame)", color=INK2, fontsize=9)
        ax.set_ylabel("test AP_IVT, frozen probe (%)", color=INK2, fontsize=9)
        ax.set_title(f"Frozen-probe score during continued pretraining from {tag.upper()}", loc="left", color=INK, fontsize=11)
        ax.set_xticks([0, 1, 2, 4] + ([8] if any(k.endswith("_ep8") for k in probes) else []))
        ax.set_xlim(-0.3, max(x for x, _ in ends) + 0.6)
        ax.legend(frameon=False, fontsize=9, labelcolor=INK2, loc="lower left")
        fig.tight_layout()
        fig.savefig(OUT / f"p2_scaling_curve_{tag}.png", dpi=160, facecolor=SURF)
        plt.close(fig)

    # Figure 2: fine-tune results vs the paper, dot + CI whisker per run
    if fts:
        names = list(fts)
        fig, ax = plt.subplots(figsize=(8.6, 0.6 * len(names) + 1.8), facecolor=SURF)
        style(ax); ax.grid(axis="x", color=GRID, linewidth=0.8); ax.grid(axis="y", visible=False)
        for i, n in enumerate(names):
            t = fts[n]["test"]["mAP_ivt"]; ci = fts[n]["test_ci95"]["ivt"]
            ax.plot(ci, [i, i], color=BLUE, linewidth=2, solid_capstyle="round", zorder=2)
            ax.plot([t], [i], "o", color=BLUE, markersize=7, markeredgecolor=SURF, markeredgewidth=1.5, zorder=3,
                    label="ours (95% CI)" if i == 0 else None)
            ax.annotate(f"{t:.1f}", (t, i), xytext=(0, 8), textcoords="offset points", ha="center", fontsize=9, color=INK,
                        bbox=dict(boxstyle="square,pad=0.1", fc=SURF, ec="none"), zorder=4)
        for j, (k, v) in enumerate(sorted(PAPER.items(), key=lambda kv: kv[1])):
            ax.axvline(v, color=ORANGE, linewidth=1, linestyle=(0, (4, 3)), zorder=1)
            ax.annotate(f"{k.split(' (')[0]} {v}", (v, len(names) - 0.35 + 0.3 * (j % 2)), fontsize=8, color=INK2,
                        ha="center", va="bottom", bbox=dict(boxstyle="square,pad=0.15", fc=SURF, ec="none"))
        ax.set_yticks(range(len(names)), [RUN_LABELS.get(n, n) for n in names])
        ax.set_ylim(-0.6, len(names) + 0.35)
        ax.set_xlabel("test AP_IVT (%), official metric — dashed: paper values", color=INK2, fontsize=9)
        fig.tight_layout(rect=(0, 0, 1, 0.92))
        fig.suptitle("Fine-tuned on CholecT50 (official recipe, full data)", x=0.01, ha="left", color=INK, fontsize=11)
        fig.savefig(OUT / "p2_finetune.png", dpi=160, facecolor=SURF)
        plt.close(fig)
    update_guide(probes, fts, teacher)
    print("\n".join(lines))


